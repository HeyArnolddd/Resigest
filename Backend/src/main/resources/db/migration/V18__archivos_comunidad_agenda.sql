-- V18: archivos subidos (fotos y comprobantes), foto del paquete, chat comunitario y agenda del conjunto.

-- Archivos guardados en la base de datos para que no se pierdan entre despliegues (máx. 5 MB cada uno).
CREATE TABLE archivo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    tipo_contenido VARCHAR(100) NOT NULL,
    tamano BIGINT NOT NULL,
    datos BYTEA NOT NULL,
    subido_por_id BIGINT REFERENCES usuario(id),
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL
);

-- Foto que toma portería al recibir el paquete
ALTER TABLE paquete ADD COLUMN foto_url VARCHAR(300);

-- Chat de todo el conjunto (un solo grupo)
CREATE TABLE mensaje_comunidad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    autor_id BIGINT NOT NULL REFERENCES usuario(id),
    contenido VARCHAR(1000) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL
);

-- Agenda del conjunto: asambleas, mantenimientos programados, trámites y eventos
CREATE TABLE evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    descripcion VARCHAR(1000),
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME,
    lugar VARCHAR(150) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    creado_por_id BIGINT NOT NULL REFERENCES usuario(id),
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL
);
