-- V7: esquema del módulo de mantenimiento (incidencias y evidencias).

CREATE TABLE incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    ubicacion VARCHAR(200),
    estado VARCHAR(20) NOT NULL,
    prioridad VARCHAR(20) NOT NULL,
    reportado_por_id BIGINT NOT NULL REFERENCES usuario(id),
    asignado_a_id BIGINT REFERENCES tecnico_mantenimiento(id),
    solucion VARCHAR(1000),
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL
);

CREATE TABLE evidencia_incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id BIGINT NOT NULL REFERENCES incidencia(id),
    url_archivo VARCHAR(500) NOT NULL,
    nombre_archivo VARCHAR(255) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL
);
