-- V4: esquema del módulo financiero (obligaciones de pago).

CREATE TABLE obligacion_financiera (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartamento_id BIGINT NOT NULL REFERENCES apartamento(id),
    concepto VARCHAR(30) NOT NULL,
    periodo VARCHAR(7) NOT NULL,
    monto_total NUMERIC(12,2) NOT NULL,
    saldo_pendiente NUMERIC(12,2) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_vencimiento DATE NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL,
    CONSTRAINT uq_obligacion_apartamento_concepto_periodo UNIQUE (apartamento_id, concepto, periodo)
);
