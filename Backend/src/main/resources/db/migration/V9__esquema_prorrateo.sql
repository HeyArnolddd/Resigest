-- V9: esquema de prorrateo de servicios comunes.

CREATE TABLE factura_servicio_comun (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL,
    periodo VARCHAR(7) NOT NULL,
    total NUMERIC(12,2) NOT NULL,
    fecha_emision DATE NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL
);

CREATE TABLE detalle_prorrateo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_id BIGINT NOT NULL REFERENCES factura_servicio_comun(id),
    apartamento_id BIGINT NOT NULL REFERENCES apartamento(id),
    valor NUMERIC(12,2) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL
);
