-- V5: tabla única de pagos (herencia SINGLE_TABLE con columna discriminadora metodo).

CREATE TABLE pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metodo VARCHAR(20) NOT NULL,
    monto NUMERIC(12,2) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL,
    referencia VARCHAR(100),
    motivo_rechazo VARCHAR(255),
    obligacion_id BIGINT NOT NULL REFERENCES obligacion_financiera(id),
    -- PagoPasarela
    id_transaccion_externa VARCHAR(100),
    url_recibo VARCHAR(255),
    -- PagoManual
    url_comprobante_adjunto VARCHAR(255),
    observacion_admin VARCHAR(255),
    validado_por_id BIGINT REFERENCES administrador(id),
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL
);
