-- V8: esquema del módulo de portería (ingresos y paquetería).

CREATE TABLE registro_ingreso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_visitante VARCHAR(200) NOT NULL,
    documento VARCHAR(50),
    tipo VARCHAR(20) NOT NULL,
    empresa VARCHAR(100),
    apartamento_destino_id BIGINT NOT NULL REFERENCES apartamento(id),
    registrado_por_id BIGINT NOT NULL REFERENCES portero(id),
    fecha_ingreso TIMESTAMP NOT NULL,
    fecha_salida TIMESTAMP,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL
);

CREATE TABLE paquete (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartamento_destino_id BIGINT NOT NULL REFERENCES apartamento(id),
    empresa_transportadora VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500),
    estado VARCHAR(20) NOT NULL,
    fecha_recepcion TIMESTAMP NOT NULL,
    fecha_entrega TIMESTAMP,
    entregado_a VARCHAR(200),
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL
);
